export interface Projection {
  cx: number;
  cy: number;
  r: number;
  lat0: number;
  lon0: number;
}

const rad = Math.PI / 180;

/**
 * Orthographic projection. Points on the far side are pulled onto the limb,
 * which keeps rings closed where a coastline crosses the horizon.
 */
export function project(p: Projection, lat: number, lon: number) {
  const phi = lat * rad;
  const phi0 = p.lat0 * rad;
  const dLon = (lon - p.lon0) * rad;
  const cosC = Math.sin(phi0) * Math.sin(phi) + Math.cos(phi0) * Math.cos(phi) * Math.cos(dLon);
  let x = Math.cos(phi) * Math.sin(dLon);
  let y = Math.cos(phi0) * Math.sin(phi) - Math.sin(phi0) * Math.cos(phi) * Math.cos(dLon);
  if (cosC < 0) {
    const len = Math.hypot(x, y) || 1;
    x /= len;
    y /= len;
  }
  return { x: p.cx + p.r * x, y: p.cy - p.r * y, visible: cosC > 0, depth: cosC };
}

export function landPaths(p: Projection): string[] {
  return LAND.map((ring) =>
    ring
      .map(([lat, lon], i) => {
        const { x, y } = project(p, lat, lon);
        return `${i === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`;
      })
      .join(" ")
      .concat(" Z"),
  );
}
