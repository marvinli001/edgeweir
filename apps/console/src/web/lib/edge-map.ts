/** Where a node's location is: its coordinates, else its country's centre; null when unknown. */
export function nodePlaceOf(
  location: { country: string; latitude: number | null; longitude: number | null } | null,
): LatLng | null {
  if (!location?.country) return null;
  if (location.latitude !== null && location.longitude !== null)
    return [location.latitude, location.longitude];
  return COUNTRY_CENTRES[location.country] ?? null;
}
