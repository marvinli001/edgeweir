// Generates src/web/components/effects/world-dots.ts: the land of the world as a dot grid
// (equirectangular, latitudes -58 to 80), computed once here with dotted-map (MIT, Basile
// Bruneau; Natural Earth land data) so the browser only draws a path. Run after changing the grid:
//   node scripts/generate-world-dots.mjs
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import DottedMap from "dotted-map";

const LAT = { min: -58, max: 80 };
const map = new DottedMap({
  height: 66,
  grid: "diagonal",
  projection: { name: "equirectangular" },
  region: { lat: LAT, lng: { min: -180, max: 180 } },
});
const points = map.getPoints();
const width = Math.ceil(Math.max(...points.map((p) => p.x))) + 1;
const height = Math.ceil(Math.max(...points.map((p) => p.y))) + 1;
const round = (n) => Math.round(n * 10) / 10;
// One subpath per dot: a zero-length segment drawn with round caps.
const path = points.map((p) => `M${round(p.x)} ${round(p.y)}h0`).join("");

const source = `// Generated by scripts/generate-world-dots.mjs (dotted-map, Natural Earth land). Do not edit.
/** Land as a dot grid: equirectangular, longitudes -180 to 180, latitudes ${LAT.min} to ${LAT.max}. */
export const WORLD_DOTS = {
  width: ${width},
  height: ${height},
  latitudes: [${LAT.min}, ${LAT.max}] as const,
  path: "${path}",
};
`;
writeFileSync(resolve(import.meta.dirname, "../src/web/components/effects/world-dots.ts"), source);
console.log(`${points.length} dots, ${width}×${height}, ${source.length} bytes`);
